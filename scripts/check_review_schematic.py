#!/usr/bin/env python3
"""Verify exported connectivity and classify known OPEN ERC issues, not hardware."""
import csv
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
HW=ROOT/'hardware'
tree=ET.parse(HW/'exports/auto_gauge.net.xml').getroot()
nodes={}
for net in tree.findall('./nets/net'):
    for node in net.findall('node'):
        key=(node.get('ref'),node.get('pin'))
        assert key not in nodes, ('Pin in multiple nets',key)
        nodes[key]=net.get('name')
matrix=list(csv.DictReader((HW/'pin_matrix.csv').open()))
checked=0
for row in matrix:
    if row['reference'].startswith('#'):continue
    expected=row['net'];actual=nodes.get((row['reference'],row['pin']))
    if expected not in ('NC','OPEN'):
        assert actual==expected,(row,actual)
        checked+=1
    else:
        assert actual is None or actual.startswith('unconnected-'),(row,actual)

def same(*pins):
    nets=[nodes.get(pin) for pin in pins]
    assert all(nets) and len(set(nets))==1,(pins,nets)
same(('U301','4'),('U401','1'))
same(('U301','5'),('U401','4'))
same(('U401','13'),('J101','4'),('J100','6'))
same(('U401','12'),('J101','5'),('J100','14'))
same(('U401','3'),('L202','2'),('U701','3'))
assert nodes[('U401','3')]=='5V_OBD'
assert nodes[('U701','6')]=='USB_5V_PROTECTED_TBD'
assert nodes[('J701','A4')]=='USB_VBUS_RAW'
assert nodes[('J701','A4')]!=nodes[('U701','6')]
same(('U301','13'),('R704','2'))
same(('U301','14'),('R703','2'))
same(('J701','A6'),('J701','B6'),('R703','1'))
same(('J701','A7'),('J701','B7'),('R704','1'))
assert nodes[('J701','A5')]!=nodes[('J701','B5')]
same(('U601','6'),('U301','12'),('R602','2'))
same(('U601','4'),('U301','17'),('R601','2'))
for pin in ('28','29','30'):
    assert nodes.get(('U301',pin),'unconnected-').startswith('unconnected-')
for ref in ('U201','U203','U601'):
    pin_numbers={p for r,p in nodes if r==ref}
    assert pin_numbers
bom=list(csv.DictReader((HW/'schematic_bom_review.csv').open()))
assert len({p['reference'] for p in bom})==len(bom)
assert not any(p['reference'].startswith('R') and re.fullmatch(r'120\s*(?:R|ohm|Ω)?',p['value'],re.I) for p in bom)
assert not list(HW.glob('*.kicad_pcb')), 'No PCB layout is authorized/generated by this workflow'

erc=json.loads((HW/'exports/erc.json').read_text())
assert isinstance(erc.get('sheets'),list) and erc['sheets'], 'Missing hierarchical ERC results; refuse an empty/flattened MCP summary'
expected_power={('U201','22'),('U202','2'),('U301','2'),('U401','3'),('U701','6')}
counts={}
severities={}
for sheet in erc['sheets']:
    for violation in sheet['violations']:
        kind=violation['type'];counts[kind]=counts.get(kind,0)+1
        severity=violation['severity'];severities[severity]=severities.get(severity,0)+1
        descriptions=' '.join(i['description'] for i in violation['items'])
        if kind=='pin_not_connected':assert 'J501' in descriptions,violation
        elif kind=='power_pin_not_driven':
            assert any(f'Symbol {r} Pin {p} ' in descriptions for r,p in expected_power),violation
        elif kind=='isolated_pin_label':assert any(n in descriptions for n in ['USB_PRESENT_SAFE_TBD','OBD_PRESENT_SAFE_TBD']),violation
        else:raise AssertionError(('Unexpected ERC finding',violation))
# A0 deliberately includes these incomplete circuits. A zero-result summary
# cannot be accepted as evidence that the real hierarchical report is clean.
assert counts==dict(pin_not_connected=31,power_pin_not_driven=5,isolated_pin_label=2), ('A0 ERC baseline changed; inspect raw report',counts)
assert severities==dict(error=36,warning=2), ('A0 ERC severity baseline changed',severities)
report=dict(scope='CONNECTIVITY CHECK ONLY; no electrical/automotive approval',
            checked_assigned_pins=checked,placed_symbols=len(bom),matrix_rows=len(matrix),
            erc_counts=counts,erc_severities=severities,erc_status='OPEN FINDINGS REMAIN; NOT CLEAN / NOT WAIVED',
            no_can_termination_120ohm=True,no_reserved_memory_gpio_assigned=True,
            usb_vbus_protection_gap_preserved=True,no_pcb_generated=True,
            independent_peer_review='NOT_PERFORMED')
review_path=HW/'reviews/A0_INDEPENDENT_REVIEW.md'
if review_path.is_file():
    report['independent_peer_review']='LIMITED_DOCUMENTARY_REVIEW'
    report['independent_review_file']=str(review_path.relative_to(HW))
    report['independent_review_sha256']=hashlib.sha256(review_path.read_bytes()).hexdigest()
(HW/'exports/connectivity_audit.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
